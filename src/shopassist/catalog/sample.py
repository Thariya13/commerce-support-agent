def raw_records() -> list[dict]:
    records = []
    for asin, title, brand, price, rating, count, path, features, description, details in RAW:
        records.append(
            {
                "main_category": "AMAZON FASHION",
                "title": title,
                "average_rating": rating,
                "rating_number": count,
                "features": features,
                "description": description,
                "price": price,
                "images": [],
                "videos": [],
                "store": brand,
                "categories": ROOT + path,
                "details": details,
                "parent_asin": asin,
                "bought_together": None,
            }
        )
    return records


def build_sample_catalog() -> list[Product]:
    products = []
    for record in raw_records():
        product = record_to_product(record, usd_to_eur=1.0, min_ratings=1)
        if product is None:
            raise ValueError(f"Fixture {record['parent_asin']} was rejected by the enrichment pipeline")
        products.append(product.model_copy(update={"source": "synthetic_fixture", "source_url": None}))
    return products


if __name__ == "__main__":
    count = write_jsonl(build_sample_catalog(), SAMPLE_CATALOG)
    print(f"Wrote {count} fixture products to {SAMPLE_CATALOG}")
